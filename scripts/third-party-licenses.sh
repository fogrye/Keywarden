#!/bin/zsh
# Regenerates Sources/Keywarden/ThirdPartyLicenses.txt, the license notices for
# every Rust crate linked into the app. Run it after changing RustIpc's
# dependencies; `--check` fails if the committed file is out of date.
set -euo pipefail

root=${0:A:h:h}
out=$root/Sources/Keywarden/ThirdPartyLicenses.txt
manifest=$root/RustIpc/Cargo.toml

notices=$(cargo tree --manifest-path $manifest --locked -e normal \
  --target aarch64-apple-darwin --prefix none -f '{p}' \
| python3 -c '
import json, os, re, subprocess, sys

meta = json.loads(subprocess.run(
    ["cargo", "metadata", "--manifest-path", sys.argv[1], "--format-version", "1", "--locked"],
    check=True, capture_output=True, text=True).stdout)
by_id = {(p["name"], p["version"]): p for p in meta["packages"]}
names = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)", re.I)

linked = set()
for line in sys.stdin:
    parts = line.split()
    if len(parts) >= 2 and parts[0] != "bridge_ipc":
        linked.add((parts[0], parts[1].lstrip("v")))

def license_files(manifest):
    # Crates from a git checkout keep their license at the repository root.
    d = os.path.dirname(manifest)
    for _ in range(4 if "/git/checkouts/" in d else 1):
        found = sorted(f for f in os.listdir(d) if names.match(f) and os.path.isfile(os.path.join(d, f)))
        if found:
            return [os.path.join(d, f) for f in found]
        if os.path.isdir(os.path.join(d, ".git")) or os.path.dirname(d) == d:
            break
        d = os.path.dirname(d)
    return []

rows = [by_id[k] for k in sorted(linked) if k in by_id]

# Many crates ship the same text (Apache-2.0 especially), so each distinct
# text is printed once, headed by the crates it belongs to.
texts = {}
missing = []
for p in rows:
    crate = "%s %s" % (p["name"], p["version"])
    files = license_files(p["manifest_path"])
    if not files:
        missing.append(p)
    for f in files:
        text = open(f, encoding="utf-8", errors="replace").read().strip()
        texts.setdefault(text, []).append(crate)

print("Keywarden third-party licenses")
print()
print("Keywarden is licensed under the GNU General Public License v3.0 only.")
print("It links the Rust crates listed below. Their license texts follow.")
print("Generated by scripts/third-party-licenses.sh; do not edit by hand.")
print()
print("Many of its translations come from the Bitwarden clients (https://github.com/bitwarden/clients),")
print("Copyright Bitwarden Inc. and its Crowdin translators, licensed under the GNU General Public")
print("License v3.0, at the commit pinned in scripts/import-bitwarden-translations.py.")
print()
for p in rows:
    source = p.get("repository") or ""
    print("  %s %s  %s  %s" % (p["name"], p["version"], p.get("license") or "", source))
for p in missing:
    print()
    print("%s %s ships no license file; it is licensed %s (%s)." % (
        p["name"], p["version"], p.get("license"), p.get("repository") or "no repository"))
for text, crates in texts.items():
    print()
    print("=" * 78)
    for crate in sorted(set(crates)):
        print(crate)
    print("=" * 78)
    print()
    print(text)
' $manifest)

if [[ ${1:-} == --check ]]; then
  if [[ $notices != "$(<$out)" ]]; then
    print -u2 "ThirdPartyLicenses.txt is out of date; run scripts/third-party-licenses.sh"
    exit 1
  fi
else
  print -r -- $notices > $out
  print "Wrote ${out#$root/}"
fi
