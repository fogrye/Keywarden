#!/usr/bin/env python3
"""Writes the locked shield as plain filled paths, in two forms:

  make-symbol.py SYMBOL_SVG MENU_BAR_SVG

- SYMBOL_SVG: a custom SF Symbol. Settings toolbar tabs draw only symbol images.
- MENU_BAR_SVG: Branding/MenuBarLocked.svg, for the menu bar and lock screen. It must not use an
  SVG mask: AppKit draws a PDF with a soft mask as empty, which left the menu bar icon blank.

The shape is one path: the shield, the key as one contour wound the other way (a hole), and the
key's ring as an island inside it.
"""
import math
import sys

# Design space: the 100 x 100 box of the Branding SVGs. Symbol space: Regular-M, baseline at y = 0.
SCALE = 0.9
SIDE_BEARING = 3.0


def to_symbol(x, y):
    return ((x - 12) * SCALE + SIDE_BEARING, (y - 96) * SCALE + 7)


def key_to_design(x, y):
    # translate(50 52) scale(0.6) rotate(45) translate(-50 -50), as in the Branding SVGs.
    x, y = x - 50, y - 50
    c, s = math.cos(math.radians(45)), math.sin(math.radians(45))
    x, y = x * c - y * s, x * s + y * c
    return x * 0.6 + 50, y * 0.6 + 52


def fmt(p):
    return f"{p[0]:.3f} {p[1]:.3f}"


def contour(commands, point_map, radius_scale):
    """commands: ("M"|"L", (x, y)) or ("A", r, large, sweep, (x, y)); mapped to absolute symbol space."""
    out = []
    for command in commands:
        if command[0] in "ML":
            out.append(f"{command[0]}{fmt(point_map(*command[1]))}")
        else:
            _, r, large, sweep, p = command
            r = r * radius_scale
            out.append(f"A{r:.3f} {r:.3f} 0 {large} {sweep} {fmt(point_map(*p))}")
    return " ".join(out) + " Z"


def shield(point_map, scale):
    d = [("M", (50, 4)), ("L", (88, 16)), ("L", (88, 46))]
    out = contour(d, point_map, scale)[:-2]
    beziers = [((88, 72), (70, 88), (50, 96)), ((30, 88), (12, 72), (12, 46))]
    for bezier in beziers:
        out += " C" + " ".join(fmt(point_map(*p)) for p in bezier)
    return out + f" L{fmt(point_map(12, 16))} Z"


def shape(point_map, scale):
    """The whole locked shield as one path's data, mapped out of the design box."""
    key_map = lambda x, y: point_map(*key_to_design(x, y))
    return " ".join([shield(point_map, scale), contour(KEY, key_map, 0.6 * scale),
                     contour(RING, key_map, 0.6 * scale)])


# Counter-clockwise (the shield is clockwise), so the key is cut out.
KEY = [
    ("M", (55.5, 47.27)), ("A", 21, 1, 0, (44.5, 47.27)),
    ("L", (44.5, 94)), ("L", (55.5, 94)), ("L", (55.5, 92)), ("L", (63, 92)), ("L", (63, 84)),
    ("L", (55.5, 84)), ("L", (55.5, 79)), ("L", (67, 79)), ("L", (67, 71)), ("L", (55.5, 71)),
]
# Clockwise again, so the ring's hole is filled back in (it shows the shield through the key).
RING = [("M", (59, 25)), ("A", 9, 1, 1, (41, 25)), ("A", 9, 1, 1, (59, 25))]

width = 76 * SCALE + 2 * SIDE_BEARING
left = 1391.0

guide = 'style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;"'
svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<!-- Generated by Branding/make-symbol.py. Do not edit. -->
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="3300" height="2200">
 <g id="Notes">
  <text id="template-version" style="stroke:none;fill:black;font-family:sans-serif;font-size:13" transform="matrix(1 0 0 1 3036 1933)">Template v.3.0</text>
 </g>
 <g id="Guides">
  <line id="Baseline-S" {guide} x1="263" x2="3036" y1="696" y2="696"/>
  <line id="Capline-S" {guide} x1="263" x2="3036" y1="625.541" y2="625.541"/>
  <line id="Baseline-M" {guide} x1="263" x2="3036" y1="1126" y2="1126"/>
  <line id="Capline-M" {guide} x1="263" x2="3036" y1="1055.54" y2="1055.54"/>
  <line id="Baseline-L" {guide} x1="263" x2="3036" y1="1556" y2="1556"/>
  <line id="Capline-L" {guide} x1="263" x2="3036" y1="1485.54" y2="1485.54"/>
  <line id="left-margin-Regular-M" {guide} x1="{left:.3f}" x2="{left:.3f}" y1="1030.79" y2="1150.12"/>
  <line id="right-margin-Regular-M" {guide} x1="{left + width:.3f}" x2="{left + width:.3f}" y1="1030.79" y2="1150.12"/>
 </g>
 <g id="Symbols">
  <g id="Regular-M" transform="matrix(1 0 0 1 {left:.3f} 1126)">
   <path d="{shape(to_symbol, SCALE)}"/>
  </g>
 </g>
</svg>
'''
open(sys.argv[1], "w").write(svg)

# The menu bar icon keeps the Branding box, shrunk to 94% around its centre like MenuBarUnlocked.svg.
MENU_BAR_SCALE = 0.94
to_menu_bar = lambda x, y: ((x - 50) * MENU_BAR_SCALE + 50, (y - 50) * MENU_BAR_SCALE + 50)
open(sys.argv[2], "w").write(f'''<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100" viewBox="0 0 100 100">
  <!-- Generated by Branding/make-symbol.py. Menu bar icon while the vault is locked: a solid shield
       with the key cut out. Template image; no masks, which AppKit can't draw in a PDF. -->
  <path d="{shape(to_menu_bar, MENU_BAR_SCALE)}"/>
</svg>
''')
